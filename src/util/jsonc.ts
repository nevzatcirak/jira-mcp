/**
 * Dependency-free JSONC (JSON with comments) parsing for config files.
 *
 * Supports exactly what a hand-edited config file needs:
 * - `//` line comments and `/* ... *\/` block comments (kept out of strings)
 * - trailing commas in objects and arrays
 */

/** Remove `//` and `/* *\/` comments while preserving string literals. */
export function stripJsoncComments(text: string): string {
  let out = "";
  let i = 0;
  let inString = false;
  while (i < text.length) {
    const ch = text[i];
    if (inString) {
      out += ch;
      if (ch === "\\" && i + 1 < text.length) {
        out += text[i + 1];
        i += 2;
        continue;
      }
      if (ch === '"') inString = false;
      i += 1;
      continue;
    }
    if (ch === '"') {
      inString = true;
      out += ch;
      i += 1;
      continue;
    }
    if (ch === "/" && text[i + 1] === "/") {
      while (i < text.length && text[i] !== "\n") i += 1;
      continue; // keep the newline itself
    }
    if (ch === "/" && text[i + 1] === "*") {
      i += 2;
      while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i += 1;
      i += 2;
      continue;
    }
    out += ch;
    i += 1;
  }
  return out;
}

/** Drop commas immediately followed (after whitespace) by `}` or `]`. */
function removeTrailingCommas(text: string): string {
  let out = "";
  let inString = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (inString) {
      out += ch;
      if (ch === "\\" && i + 1 < text.length) {
        out += text[i + 1];
        i += 1;
      } else if (ch === '"') {
        inString = false;
      }
      continue;
    }
    if (ch === '"') {
      inString = true;
      out += ch;
      continue;
    }
    if (ch === ",") {
      let j = i + 1;
      while (j < text.length && /\s/.test(text[j])) j += 1;
      if (text[j] === "}" || text[j] === "]") continue; // trailing comma — drop
    }
    out += ch;
  }
  return out;
}

/** Parse JSONC text (comments + trailing commas tolerated) into a value. */
export function parseJsonc(text: string): unknown {
  return JSON.parse(removeTrailingCommas(stripJsoncComments(text)));
}
